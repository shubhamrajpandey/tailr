/**
 * Generates LaTeX document preamble, packages, and custom ATS formatting commands.
 */
export function renderLatexPreamble(): string {
  return `%-------------------------
% ATS-Friendly Resume
% Auto-Generated by Tailr ATS Engine
%-------------------------

\\documentclass[letterpaper,11pt]{article}

\\usepackage[empty]{fullpage}
\\usepackage{titlesec}
\\usepackage{enumitem}
\\usepackage[hidelinks]{hyperref}
\\usepackage{fancyhdr}
\\usepackage[english]{babel}
\\usepackage{tabularx}
\\usepackage{fontawesome5}
\\usepackage{setspace}

\\pagestyle{fancy}
\\fancyhf{}
\\fancyfoot{}
\\renewcommand{\\headrulewidth}{0pt}
\\renewcommand{\\footrulewidth}{0pt}

% ---------- PAGE LAYOUT ----------
\\addtolength{\\oddsidemargin}{-0.5in}
\\addtolength{\\evensidemargin}{-0.5in}
\\addtolength{\\textwidth}{1in}
\\addtolength{\\topmargin}{-0.65in}
\\addtolength{\\textheight}{1.55in}

\\urlstyle{same}
\\raggedright
\\setlength{\\tabcolsep}{0in}
\\setstretch{0.97}

% ---------- SECTION FORMATTING ----------
\\titleformat{\\section}{
  \\vspace{-6pt}\\scshape\\raggedright\\large
}{}{0em}{}[\\titlerule \\vspace{-8pt}]

% ---------- CUSTOM COMMANDS ----------
\\newcommand{\\resumeItem}[1]{
  \\item\\small{#1}
}

\\newcommand{\\resumeSubheading}[4]{
  \\item
  \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}
    \\textbf{#1} & #2 \\\\
    \\textit{\\small#3} & \\textit{\\small #4} \\\\
  \\end{tabular*}
}

\\newcommand{\\resumeProjectHeading}[3]{
  \\item
  \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}
    \\small\\textbf{#1} \\small{$|$ \\href{#2}{\\underline{Live Demo}}} & \\small #3 \\\\
  \\end{tabular*}
}

\\newcommand{\\resumeSubHeadingListStart}{\\begin{itemize}[leftmargin=0.15in, label={}]}
\\newcommand{\\resumeSubHeadingListEnd}{\\end{itemize}}
\\newcommand{\\resumeItemListStart}{\\begin{itemize}[itemsep=1pt]}
\\newcommand{\\resumeItemListEnd}{\\end{itemize}}`;
}

/**
 * Renders the top contact and social links header block.
 */
export function renderHeaderSection(basics: StructuredResumeData["basics"]): string {
  const headerLinks: string[] = [];
  if (basics.email) headerLinks.push(`\\href{mailto:${basics.email}}{${escapeLatex(basics.email)}}`);
  if (basics.linkedinUrl) headerLinks.push(`\\href{${basics.linkedinUrl}}{LinkedIn}`);
  if (basics.githubUrl) headerLinks.push(`\\href{${basics.githubUrl}}{GitHub}`);
  if (basics.portfolioUrl) headerLinks.push(`\\href{${basics.portfolioUrl}}{Portfolio}`);

  const linksLine = headerLinks.join(" $|$\n  ");

  return `\\begin{center}
  {\\Huge \\scshape ${escapeLatex(basics.fullName)}} \\\\ \\vspace{4pt}
  \\small
  ${linksLine} \\\\
  ${escapeLatex(basics.location || "")}
\\end{center}`;
}

/**
 * Renders the career summary section.
 */
export function renderCareerSummarySection(summary?: string): string {
  if (!summary) return "";
  return `\\section{Career Summary}
${escapeLatex(summary)}`;
}

/**
 * Renders the categorized technical skills section.
 */
export function renderSkillsSection(skills?: StructuredResumeData["technicalSkills"]): string {
  if (!skills || skills.length === 0) return "";
  const skillsLines = skills
    .map((item) => {
      const skillsStr = Array.isArray(item.skills) ? item.skills.join(", ") : item.skills;
      return `  \\resumeItem{\\textbf{${escapeLatex(item.category)}:} ${escapeLatex(skillsStr)}}`;
    })
    .join("\n");

  return `\\section{Technical Skills}
\\resumeSubHeadingListStart
${skillsLines}
\\resumeSubHeadingListEnd`;
}

/**
 * Renders the professional work experience section.
 */
export function renderExperienceSection(experience?: StructuredResumeData["workExperience"]): string {
  if (!experience || experience.length === 0) return "";
  const expLines = experience
    .map((exp) => {
      const bulletItems = (exp.bullets || [])
        .map((bullet) => `      \\resumeItem{${escapeLatex(bullet)}}`)
        .join("\n");

      return `  \\resumeSubheading
    {${escapeLatex(exp.role)}}{${escapeLatex(exp.startDate)} -- ${escapeLatex(exp.endDate)}}
    {${escapeLatex(exp.company)}}{${escapeLatex(exp.location || "")}}
    \\resumeItemListStart
${bulletItems}
    \\resumeItemListEnd`;
    })
    .join("\n\n");

  return `\\section{Work Experience}
\\resumeSubHeadingListStart
${expLines}
\\resumeSubHeadingListEnd`;
}

/**
 * Renders the academic education credentials section.
 */
export function renderEducationSection(education?: StructuredResumeData["education"]): string {
  if (!education || education.length === 0) return "";
  const eduLines = education
    .map((edu) => {
      return `  \\resumeSubheading
    {${escapeLatex(edu.institution)}}{${escapeLatex(edu.location || "")}}
    {${escapeLatex(edu.degree)}}{${escapeLatex(edu.startDate || "")}${edu.endDate ? ` -- ${escapeLatex(edu.endDate)}` : ""}}`;
    })
    .join("\n\n");

  return `\\section{Education}
\\resumeSubHeadingListStart
${eduLines}
\\resumeSubHeadingListEnd`;
}

/**
 * Renders the portfolio projects section.
 */
export function renderProjectsSection(projects?: StructuredResumeData["projects"]): string {
  if (!projects || projects.length === 0) return "";
  const projectLines = projects
    .map((proj) => {
      const headerTitle = proj.technologies
        ? `${escapeLatex(proj.title)} $|$ ${escapeLatex(proj.technologies)}`
        : escapeLatex(proj.title);

      const bulletItems = (proj.bullets || [])
        .map((bullet) => `      \\resumeItem{${escapeLatex(bullet)}}`)
        .join("\n");

      return `  \\resumeProjectHeading
    {${headerTitle}}
    {${proj.liveUrl || "#"}}
    {${escapeLatex(proj.year || "")}}
    \\resumeItemListStart
${bulletItems}
    \\resumeItemListEnd`;
    })
    .join("\n\n");

  return `\\section{Projects}
\\resumeSubHeadingListStart
${projectLines}
\\resumeSubHeadingListEnd`;
}

/**
 * Compiles structured resume data into standard ATS-friendly LaTeX source code.
 * Composes isolated, modular section renderers to avoid deep nesting.
 */
export function generateLatexFromStructuredResume(data: StructuredResumeData): string {
  const sections = [
    renderLatexPreamble(),
    "\\begin{document}",
    renderHeaderSection(data.basics),
    renderCareerSummarySection(data.careerSummary),
    renderSkillsSection(data.technicalSkills),
    renderExperienceSection(data.workExperience),
    renderEducationSection(data.education),
    renderProjectsSection(data.projects),
    "\\end{document}",
  ].filter(Boolean);

  return sections.join("\n\n").trim();
}
